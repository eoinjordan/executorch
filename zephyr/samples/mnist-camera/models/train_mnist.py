"""Train TinyDigitNet on MNIST and export it for the Zephyr sample.

Outputs (paths relative to the repo root by default):
  firmware/model/mnist_tiny.pte      ExecuTorch program, portable fp32 ops
  firmware/src/test_input.h          one MNIST test image + reference logits
  train/out/mnist_tiny.pt            PyTorch state_dict (for re-export)

Usage:
  python train/train_mnist.py                          # 2 epochs, ~1-2 min on CPU
  python train/train_mnist.py --epochs 1 --limit 10000 # quick smoke run
"""

import argparse
import pathlib
import sys

import torch
import torch.nn.functional as F
from torch.utils.data import DataLoader, Subset
from torchvision import datasets, transforms

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from tiny_digit_net import INPUT_SHAPE, MEAN, STD, TinyDigitNet  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parents[1]


def get_loaders(data_dir: pathlib.Path, batch_size: int, limit: int):
    tf = transforms.Compose([transforms.ToTensor(), transforms.Normalize((MEAN,), (STD,))])
    train_ds = datasets.MNIST(data_dir, train=True, download=True, transform=tf)
    test_ds = datasets.MNIST(data_dir, train=False, download=True, transform=tf)
    if limit:
        train_ds = Subset(train_ds, range(min(limit, len(train_ds))))
    return (
        DataLoader(train_ds, batch_size=batch_size, shuffle=True),
        DataLoader(test_ds, batch_size=1000),
        test_ds,
    )


def train(model, loader, epochs: int, lr: float):
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    model.train()
    for epoch in range(epochs):
        total, correct, loss_sum = 0, 0, 0.0
        for x, y in loader:
            opt.zero_grad()
            out = model(x)
            loss = F.cross_entropy(out, y)
            loss.backward()
            opt.step()
            loss_sum += loss.item() * len(y)
            correct += (out.argmax(1) == y).sum().item()
            total += len(y)
        print(f"epoch {epoch + 1}/{epochs}: loss={loss_sum / total:.4f} acc={correct / total:.4f}")


@torch.no_grad()
def evaluate(model, loader) -> float:
    model.eval()
    correct = total = 0
    for x, y in loader:
        correct += (model(x).argmax(1) == y).sum().item()
        total += len(y)
    return correct / total


def export_pte(model, out: pathlib.Path) -> None:
    """torch.export -> Edge dialect -> ExecuTorch program, no backend delegate.

    Every op is lowered to the portable kernel library, which is what the
    Zephyr module builds with the portable kernels (no backend delegate).
    """
    from executorch.exir import EdgeCompileConfig, to_edge_transform_and_lower

    model.eval()
    example = (torch.zeros(*INPUT_SHAPE),)
    exported = torch.export.export(model, example)
    program = to_edge_transform_and_lower(
        exported,
        compile_config=EdgeCompileConfig(_check_ir_validity=False),
    ).to_executorch()

    ops = sorted(
        {
            str(n.target)
            for n in program.exported_program().graph.nodes
            if n.op == "call_function"
        }
    )
    print("operators in program:")
    for op in ops:
        print(f"  {op}")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(program.buffer)
    print(f"wrote {out} ({out.stat().st_size} bytes)")


@torch.no_grad()
def write_test_header(model, test_ds, index: int, out: pathlib.Path) -> None:
    """Embed one test image and the PyTorch logits so the firmware can self-check."""
    model.eval()
    img, label = test_ds[index]
    logits = model(img[None])[0]
    pixels = img.flatten().tolist()

    # ASCII preview of the digit in the header comment.
    raw = (img[0] * STD + MEAN).clamp(0, 1)
    preview = "\n".join(
        " * " + "".join("#" if v > 0.5 else ("+" if v > 0.2 else ".") for v in row)
        for row in raw.tolist()
    )

    lines = [
        "/* Generated by train/train_mnist.py. Do not edit.",
        f" * MNIST test index {index}, label {label}.",
        preview,
        " */",
        "#pragma once",
        "",
        f"#define TEST_INPUT_LABEL {label}",
        f"#define TEST_INPUT_NUMEL {len(pixels)}",
        "",
        "/* Normalised with (x/255 - MEAN) / STD, NCHW [1,1,28,28]. */",
        "static const float kTestInput[TEST_INPUT_NUMEL] = {",
    ]
    for i in range(0, len(pixels), 7):
        lines.append("    " + ", ".join(f"{v:.6f}f" for v in pixels[i : i + 7]) + ",")
    lines += [
        "};",
        "",
        "/* Reference logits from PyTorch for kTestInput. */",
        "static const float kTestExpectedLogits[10] = {",
        "    " + ", ".join(f"{v:.6f}f" for v in logits.tolist()) + ",",
        "};",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out} (label={label}, argmax={int(logits.argmax())})")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--epochs", type=int, default=2)
    p.add_argument("--lr", type=float, default=1e-3)
    p.add_argument("--batch-size", type=int, default=64)
    p.add_argument("--limit", type=int, default=0, help="use only the first N training images")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--data-dir", type=pathlib.Path, default=REPO / "models" / "data")
    p.add_argument("--pte", type=pathlib.Path, default=REPO / "models" / "mnist_tiny.pte")
    p.add_argument("--header", type=pathlib.Path, default=REPO / "src" / "test_input.h")
    p.add_argument("--state-dict", type=pathlib.Path, default=REPO / "models" / "mnist_tiny.pt")
    p.add_argument("--test-index", type=int, default=0)
    args = p.parse_args()

    torch.manual_seed(args.seed)
    train_loader, test_loader, test_ds = get_loaders(args.data_dir, args.batch_size, args.limit)

    model = TinyDigitNet()
    n_params = sum(t.numel() for t in model.parameters())
    print(f"TinyDigitNet: {n_params} parameters ({n_params * 4 / 1024:.1f} KiB fp32)")

    train(model, train_loader, args.epochs, args.lr)
    print(f"test accuracy: {evaluate(model, test_loader):.4f}")

    args.state_dict.parent.mkdir(parents=True, exist_ok=True)
    torch.save(model.state_dict(), args.state_dict)

    export_pte(model, args.pte)
    write_test_header(model, test_ds, args.test_index, args.header)


if __name__ == "__main__":
    main()
